export interface BufferExperimentResult {
  trace: BufferTrace;
  mechanism: BufferMechanism;
  candidate: SchemaCandidate;
  order: DeliveryOrder;
  status: "PASS" | "FAIL";
  difference: string | null;
  history: string[];
  observed: unknown;
}

export interface BufferExperimentReport {
  cases: BufferExperimentResult[];
  probes: BufferProbeEvidence[];
  replacements: BufferProbeEvidence[];
  files: Map<string, string>;
  markdown: string;
}

function historyName(trace: string): string {
  return `histories/${trace}.md`;
}

function cell(mechanism: BufferMechanism, trace: BufferTrace, cases: BufferExperimentResult[]): string {
  const group = cases.filter(result => result.mechanism === mechanism && result.trace === trace);
  const failed = group.filter(result => result.status === "FAIL");
  return failed.length === 0 ? `PASS (${group.length}/${group.length})` : failed.map(result => `FAIL [${result.candidate} ${result.order}](${historyName(`${trace.replaceAll(" ", "-")}-${mechanism}-${result.candidate}-${result.order}`)})`).join(", ");
}

function probeHistory(probes: BufferProbeEvidence[]): string {
  const first = probes.find(probe => probe.status === "FAIL") ?? probes[0];
  if (!first) throw new Error("Empty probe history");
  const observed = first.observed as Record<string, unknown>;
  return [
    first.shows,
    "",
    "Generated by `node src/buffer-report.ts --write`; replay with `npm test` or `npm run experiments`. Literal expected states remain in `test/buffer-oracles.ts`.",
    "",
    "| Candidate | Mechanism | Delivery | Result | First difference |",
    "| --- | --- | --- | --- | --- |",
    ...probes.map(probe => `| ${probe.candidate} | ${probe.mechanism} | ${probe.order} | ${probe.status} | ${probe.difference ?? "oracle matched"} |`),
    "",
    `Representative history: candidate ${first.candidate}, ${first.mechanism}, ${first.order}.`,
    "",
    "```text",
    ...first.history,
    "```",
    "",
    "Alice's observed state at the failure (E and N are distinct only in M3):",
    "",
    "```json",
    JSON.stringify(observed.A, null, 2),
    "```",
    ""
  ].join("\n");
}

export function runBufferExperiments(): BufferExperimentReport {
  const cases: BufferExperimentResult[] = [];
  const probes: BufferProbeEvidence[] = [];
  const replacements: BufferProbeEvidence[] = [];
  const files = new Map<string, string>();
  for (const trace of bufferTraceOrder) {
    for (const mechanism of bufferMechanisms) {
      for (const candidate of ["A", "B"] as const) {
        for (const order of bufferOracles[trace].orders) {
          const harness = new BufferHarness(candidate, mechanism, bufferOracles[trace].seed);
          try {
            let difference: string | null = null;
            try {
              const names = stageTrace(harness, trace, order);
              finishTrace(harness, trace, order, names);
            } catch (error) {
              if (!(error instanceof Error)) throw error;
              difference = error.message;
            }
            const result: BufferExperimentResult = { trace, mechanism, candidate, order, status: difference ? "FAIL" : "PASS", difference, history: harness.history(), observed: observeBuffers(harness) };
            cases.push(result);
            if (difference) files.set(historyName(`${trace.replaceAll(" ", "-")}-${mechanism}-${candidate}-${order}`), probeHistory([{ ...result, shows: `The ${trace} literal oracle failed under ${mechanism}, candidate ${candidate}, ${order}.` }]));
          } finally {
            harness.destroy();
          }
        }
      }
    }
  }
  for (const candidate of ["A", "B"] as const) {
    for (const mechanism of bufferMechanisms) {
      probes.push(probeAmbiguousDiff(candidate, mechanism));
      probes.push(probeRecapturedBase(candidate, mechanism, "T02"));
      probes.push(probeDeleteFirst(candidate, mechanism, "D1"));
      probes.push(probeDeleteFirst(candidate, mechanism, "D3"));
    }
    probes.push(probeQueueBound(candidate, "M1"), probeQueueBound(candidate, "M3"));
    probes.push(probeRecapturedBase(candidate, "M2", "T04"));
    probes.push(probeMissingRecovery(candidate), probeProviderBypass(candidate));
  }
  for (const trace of new Set(probes.map(probe => probe.trace))) {
    files.set(historyName(trace), probeHistory(probes.filter(probe => probe.trace === trace)));
  }
  for (const fixture of replacementIntentFixtures) {
    for (const mechanism of bufferMechanisms) {
      for (const candidate of ["A", "B"] as const) {
        for (const order of fixture.orders) {
          const harness = new BufferHarness(candidate, mechanism, [{ id: "R1", text: "the the" }]);
          try {
            let difference: string | null = null;
            try { runReplacementIntent(harness, fixture, order); }
            catch (error) {
              if (!(error instanceof Error)) throw error;
              difference = error.message;
            }
            const result: BufferProbeEvidence = { trace: fixture.name, mechanism, candidate, order, status: difference ? "FAIL" : "PASS", difference, history: harness.history(), observed: observeBuffers(harness), shows: `Target-evidenced ${fixture.name} preserves intended identities and undo selection.` };
            replacements.push(result);
            if (difference) files.set(historyName(`T03-intent-${mechanism}-${candidate}-${fixture.name.replaceAll(" ", "-")}-${order}`), probeHistory([result]));
          } finally {
            harness.destroy();
          }
        }
      }
    }
  }
  const markdown = [
    "# Stale-base experiment results",
    "",
    "The simulated editable beat retains paint-time identities, runs, epoch and beat version. Native target evidence retains which painted characters survive and which characters are new; commit plans that replacement even when its string is unchanged or its difference is nonminimal. Without target evidence, the minimal-string-diff ambiguity guard is unchanged. Synthetic composition start/update/end events keep the native buffer unchanged by remote integration. Both candidate layouts run; no DOM or real editor is used.",
    "",
    `Main traces: ${cases.filter(result => result.status === "PASS").length}/${cases.length} pass, including each row's undo outcome, carets, selections, marks and recovery list. Counts include both candidates and all listed orders. M3 checks every E and N document separately, plus late-C where listed.`,
    "",
    "| Trace | M1 | M2 | M3 | Delivery orders |",
    "| --- | --- | --- | --- | --- |",
    ...bufferTraceOrder.map(trace => `| ${trace} | ${bufferMechanisms.map(mechanism => cell(mechanism, trace, cases)).join(" | ")} | ${bufferOracles[trace].orders.join(", ")} |`),
    "",
    "Main runs use target-range evidence and insert replacements at the painted gap before deleting the selected identities. T01's composition variant is additional to the seven requested rows. T01 undo selects the restored bXc; T03 replace undo selects the restored second word. The older harness's T01 undo oracle now checks that selection too; it failed with `carets.A.selection … got <missing>` before reanchoring it.",
    "",
    "## Target-evidenced replacement intent",
    "",
    `Additional replacement cases: ${replacements.filter(result => result.status === "PASS").length}/${replacements.length} pass, including identities, deletion of s5/s6/s7, caret, recovery and undo selection. Literal expectations are in test/buffer-replacements.ts; the original 144 results and 34 probes are unchanged.`,
    "",
    "| Replacement | M1 | M2 | M3 | Delivery orders |",
    "| --- | --- | --- | --- | --- |",
    ...replacementIntentFixtures.map(fixture => `| ${fixture.name} | ${bufferMechanisms.map(mechanism => {
      const group = replacements.filter(result => result.trace === fixture.name && result.mechanism === mechanism);
      return `${group.every(result => result.status === "PASS") ? "PASS" : "FAIL"} (${group.filter(result => result.status === "PASS").length}/${group.length})`;
    }).join(" | ")} | ${fixture.orders.join(", ")} |`),
    "",
    "Before the planner change, all 78 cases failed with 0 compatible minimal splices. Reproduce with node --test test/buffer-replacements.test.ts. Replacing s5 s6 s7 (the) with typed or pasted the now yields s1..s4 a1 a2 a3, caret after a3; undo yields s1..s4 s5* s6* s7* and selects the restored word. A concurrent n (b1) at the left gap, inside the word or at the right gap survives after a3 under D1, D3 and dup. Undo restores b1's original relation to the restored word; selection includes b1 only when it lies inside that word. Prefix/suffix replacements mint every typed identity, including unchanged letters. Paste here uses the same simulated target/data contract, without a clipboard or browser. Disjoint native targets remain uncommitted rather than deleting an untouched painted character.",
    "",
    "## Failure probes and predictions",
    "",
    "PASS below means the probe met the literal content oracle; FAIL means it hit the stated missing requirement or oracle difference. These failures are asserted by tests; they are not skipped or substituted for the main trace oracles.",
    "",
    "| Probe | M1 | M2 | M3 | History |",
    "| --- | --- | --- | --- | --- |",
    `| T02, base recaptured from the replica | FAIL | FAIL | FAIL | [history](${historyName("T02-recaptured-base")}) |`,
    `| T04, base recaptured at composition commit | E frozen by tested gate | FAIL | E frozen by tested gate | [history](${historyName("T04-recaptured-base")}) |`,
    `| T03, strings without native target ranges | FAIL | FAIL | FAIL | [history](${historyName("T03-no-target-ranges")}) |`,
    `| T04, composition held past byte bound | FAIL | no deferral queue | FAIL | [history](${historyName("T04-long-composition")}) |`,
    `| T04 removed, active-only mapping | not probed | FAIL | not probed | [history](${historyName("T04-removed-no-recovery-mapping")}) |`,
    `| T04, actual provider bypasses gate | FAIL deferral; content PASS | not probed | not probed | [history](${historyName("T04-provider-bypass")}) |`,
    `| T01 composition, delete before insert | FAIL D1/D3 | FAIL D1; PASS D3 | FAIL D1/D3 | [history](${historyName("T01-composition-delete-first")}) |`,
    "",
    "Artifact 8 §4's repeated-text failure does not occur in the main M2 run with synthetic target ranges; without those ranges the diff has four equally minimal deletions and cannot know the selected identities. This is conditional evidence for the proposed binding contract, not proof that a browser supplies those ranges reliably. The same ambiguity affects M1 and M3 if target evidence is removed.",
    "",
    "The removed-target prediction is confirmed as a recovery requirement. Soft removal retains R1's text; M2 deliberately inserts into that retained recovery context, never the neighbouring active beat. M1 and M3 integrate removal after local commit; the removal's observed identities still classify a1/a2 as Alice's unobserved edit. Undo removes only her insertion and leaves Bob's removal intact.",
    "",
    "The pinned provider's public `onMessage` path really changes M1's E during composition without entering its queue. The deferral prediction is confirmed, while a stronger claim that this necessarily corrupts T04's text is not observed: identity-mapped commit still passes. The probe disables socket connection, supplies framed inbound messages directly, and destroys provider and socket timers in finally.",
    "",
    "M1/M3 fail the deliberately tiny byte bound without dropping the overflow transport message. M3 has already integrated it into N, so the trace stops and retains N as well as the native buffer; recovery, cancellation, quotas and persistence need a separate design. The queue limit here is an injectable stress bound, not a proposed product limit. M3's main runs prove distinct N/E documents and origin-filtered forwarding with no echo messages; they do not prove crash-safe persistence or heap budgets.",
    "",
    "No schema or mechanism is selected. The real editor still needs reliable paint snapshots, beforeinput target ranges or equivalent selection evidence, synchronous stale-paint cancellation/repaint, composition binding, selection restoration and recovery routing. Provider/hydration/recovery ingress must share a gate for M1; M3 requires durable coordination of E and N. Candidate A identity scans and the exhaustive small-string splice enumerator are unmeasured and make no production performance claim. PERF, STORE, images and app/browser suites are outside this lane.",
    "",
    "Reproduce: `npm test`; `npm run experiments`; `node src/buffer-report.ts --check` checks the retained result table and histories. Expected results are unchanged literal data from artifact 8. No product status policy is exercised or selected.",
    ""
  ].join("\n");
  files.set("buffer-results.md", markdown);
  return { cases, probes, replacements, files, markdown };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const report = runBufferExperiments();
  for (const [name, contents] of report.files) {
    const path = new URL(`../${name}`, import.meta.url);
    if (process.argv.includes("--write")) writeFileSync(path, contents);
    if (process.argv.includes("--check") && readFileSync(path, "utf8") !== contents) throw new Error(`Stale experiment artifact: ${name}`);
  }
  process.stdout.write(report.markdown);
  if ([...report.cases, ...report.replacements].some(result => result.status === "FAIL")) process.exitCode = 1;
}
