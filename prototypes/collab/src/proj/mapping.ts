export const projectionFieldMapping: readonly ProjectionFieldMapping[] = shared.map(([field, location]) => ({
  field, A: location.replace("narration text and attributes", "flow between beat boundary embeds").replace("heading characters", "flow between heading boundary embeds"),
  B: location.replace("narration text and attributes", "segments[id].text after head or inner embed").replace("heading characters", "segments[id].text under heading head or embed")
}));

export function assertProjectionMapping(inventory: readonly string[], mapping: readonly ProjectionFieldMapping[]): void {
  if (mapping.length !== inventory.length) throw new Error(`Field mapping count ${mapping.length}, inventory ${inventory.length}`);
  for (const field of inventory) {
    const entries = mapping.filter(entry => entry.field === field);
    if (entries.length !== 1 || !entries[0]?.A || !entries[0]?.B) throw new Error(`Unmapped field: ${field}`);
  }
}
