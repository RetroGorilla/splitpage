import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { runBeatExperiments, runStructure, structureTraces } from "../test/structure-runner.ts";
import type { StructureRunResult } from "../test/structure-runner.ts";

export function beatReport(): { runs: StructureRunResult[]; files: Map<string, string>; markdown: string } {
  const runs = runBeatExperiments();
  const files = new Map<string, string>();
  for (const candidate of ["A", "B"] as const) {
    const probes = [false, true].map(swapped => runStructure("T06", candidate, "D1", true, swapped));
    files.set(`histories/T06-native-undo-${candidate}.md`, [
      "Plain per-writer join undo leaves the other writer's join live, so the required unjoin fails.", "",
      "Replay: `node --test test/structure.test.ts` (plain per-writer join undo).", "",
      ...probes.flatMap((run, index) => [`## ${index ? "Swapped" : "Normal"} client ids`, "", run.failure ?? "Unexpected pass", "", "```text", ...run.history, "```", ""])
    ].join("\n"));
  }
  const table = ["| Trace | Candidate A | Candidate B | Delivery orders |", "| --- | --- | --- | --- |"];
  for (const [trace, orders] of Object.entries(structureTraces)) {
    const cells = (["A", "B"] as const).map(candidate => {
      const group = runs.filter(run => run.trace === trace && run.candidate === candidate);
      const failures = group.filter(run => run.failure);
      if (!failures.length) return `PASS (${group.length}/${group.length})`;
      const path = `histories/${trace.replaceAll(" ", "-")}-${candidate}.md`;
      files.set(path, [
        `${candidate} fails the literal ${trace} oracle; expected data was not changed.`, "",
        "Replay: `node src/structure-report.ts` (all orders) or `npm test`.", "",
        ...failures.flatMap(run => [`## ${run.order}`, "", run.failure ?? "", "", "```text", ...run.history, "```", ""])
      ].join("\n"));
      return `FAIL (${group.length - failures.length}/${group.length} pass), [history](${path})`;
    });
    table.push(`| ${trace} | ${cells.join(" | ")} | ${trace === "MOVE cut-paste" ? "refusal (no delivery)" : orders.join(", ")} |`);
  }
  const markdown = [
    "# Structural beat experiment results", "",
    "Generated by `node src/structure-report.ts --write`. Literal expectations are in `test/structure-oracles.ts` and `test/oracles.ts`; generation changes no oracle.", "",
    `${runs.filter(run => !run.failure).length}/${runs.length} candidate/order runs pass; ${runs.reduce((sum, run) => sum + run.checks, 0)} replica checkpoint comparisons completed before the first failure in each run. A run stops at its first mismatch.`, "",
    ...table, "", "## Mechanisms added", "",
    "- Both candidates: retained join cancellation ids (`retiredJoins`). Undo retires every matching join known at that point and consumes exactly that command; Bob's later undo cannot reach Alice's bold. Cost: one durable flag per retired join, plus reader filtering and a semantic undo handler. These fixtures cover concurrent identical joins and a remote glue rewrite, not a later intentional rejoin.",
    "- Both candidates: top-item-only native undo. Earlier items are temporarily removed from the public `undoStack` array and restored after `undo()`. Cost: one undo wrapper; the public field has undocumented use (Y7).",
    "- Both candidates: removal classification follows observed character identities into a concurrently split beat; components retain their origin and gallery folding is projection-only. Cost: retained observed ranges and a read-time identity membership pass.", "",
    "## Predictions and limitations", "",
    "Replay each claim with `npm test` or `node src/structure-report.ts`.",
    "| Prediction | Result | Reproducer and scope |", "| --- | --- | --- |",
    "| A-H1, A-H4, A-H5, A-H11 | Confirmed | `node --test test/structure.test.ts`: T05 two splits, full T06, T07, T08; no copied narration/heading/visual identities, one glue, duplicate row embed inert |",
    "| A-H2; Y8, Y9 | Confirmed for soft removal | T10: default gc, full-state late join before undo, original and remote identities retained; no snapshot or subdocument |",
    "| A-H3 | Confirmed for T09 only | Captured observed identities classify removal; T11's split descendant is in the next report |",
    "| B-H1, B-H2, B-H3, B-H4 | Confirmed for these traces | T05/T08/T09/T12 and MOVE: segment head conversion, sole order array, per-segment deletes in one transaction, text identity survives move/undo |",
    "| Y3, Y6 | Confirmed | T08/T09/T12: carets use relative positions with followUndoneDeletions=false; deleted text restores bind new raw identities; restored selection is reanchored locally |",
    "| Y4, same-gap rule, A-H6 | Confirmed | `node --test test/harness.test.ts`: T05 runs with both client-id orders; split-side depends on client id |",
    "| Y5, A-H9 | Confirmed within T12 scope | Local origins and explicit stopCapturing separate command groups; remote edits survive undo/redo. Timeout, 200-entry cap and production grouping are not tested |",
    "| Y7 and section 4 plain-undo failure | Confirmed | `node --test test/structure.test.ts`: plain T06 fails under either client-id order; [A history](histories/T06-native-undo-A.md), [B history](histories/T06-native-undo-B.md). Cause: the other join entry remains live |",
    "| U-H1 | Confirmed with added mechanism for joins | Same script: top-item undo plus semantic retirement unjoins despite duplicate entries or a remote glue rewrite and preserves older bold/italic |",
    "| Y10 | Confirmed for boundaries | T05/T08/T12 use public insertEmbed/toDelta and recreate boundaries on native undo/redo; content atoms and PROJ remain separate |",
    "| Section 4 Candidate B T08 expected failure | Refuted for the specified create/race fixtures | Both head conversion and inner embed occur in one transaction; T08 create and race pass every listed order, including late-C |", "",
    "Candidate A refuses all movement before mutation. Both refuse cross-scene cut/paste before consuming a cut. Candidate B admits whole-segment movement only; part-segment movement is refused.",
    "Without semantic join undo both candidates fail the required T06 undo. Neither has yet proved identical simultaneous removal undo, the complete field projection, scalar status conflicts, or mark/reply recovery. A-H7/B-H5 performance and the real-editor slice are outside this report. The prototype handles only the named small fixtures; it is not a complete editor or projection. No schema is selected.", ""
  ].join("\n");
  files.set("structure-results.md", markdown);
  return { runs, files, markdown };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const report = beatReport();
  if (process.argv.includes("--write")) {
    for (const [path, content] of report.files) writeFileSync(new URL(`../${path}`, import.meta.url), content);
  } else if (process.argv.includes("--check")) {
    for (const [path, content] of report.files) {
      if (readFileSync(new URL(`../${path}`, import.meta.url), "utf8") !== content) throw new Error(`Stale ${path}`);
    }
  }
  console.log(report.markdown);
  for (const run of report.runs.filter(run => run.failure)) console.log(`${run.trace} ${run.candidate} ${run.order}: ${run.failure}`);
}
