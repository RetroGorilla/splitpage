import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { REPO, listRepoFiles } from "./source-scan.mjs";
import { isMain } from "./main-module.mjs";

export const MAP_PATH = "docs/architecture/feature-map.md";
const SHARED_FOLDERS = new Set(["common", "routing"]);
const SCRIPT = /\.(?:m?js|ts)$/;
const TEST = /(^|\/)(tests|src\/test)\/|\.test\.(?:m?js|ts)$/;

export function importsOf(path, text) {
  const out = new Set();
  for (const m of text.matchAll(/(?:\bfrom\s*|\bimport\s*\(\s*|\bimport\s+)"(\.{1,2}\/[^"]+)"/g)) {
    out.add(relative(REPO, resolve(REPO, dirname(path), m[1])).split("\\").join("/"));
  }
  return out;
}

export function featureOf(path) {
  const m = /^src\/features\/([^/]+)\//.exec(path);
  return m && !SHARED_FOLDERS.has(m[1]) ? m[1] : null;
}

export function actionIds(text) {
  return [...text.matchAll(/^\s*id:\s*"([^"]+)"/gm)].map((m) => m[1]);
}

export function buildMap(files) {
  const features = new Map();
  const entry = (name) => {
    if (!features.has(name)) features.set(name, { files: [], wiring: new Set(), ports: new Set(), actions: [], tests: new Set() });
    return features.get(name);
  };
  for (const { path, text } of files) {
    const name = featureOf(path);
    if (!name) continue;
    const f = entry(name);
    if (TEST.test(path)) f.tests.add(path);
    else f.files.push(path);
    if (/\/actions\.ts$/.test(path)) f.actions.push(...actionIds(text));
  }
  for (const { path, text } of files) {
    const imported = importsOf(path, text);
    const reached = new Set([...imported].map(featureOf).filter(Boolean));
    const folder = /^tests\/features\/([^/]+)\//.exec(path)?.[1];
    if (folder && features.has(folder)) reached.add(folder);
    for (const name of reached) {
      const f = features.get(name);
      if (!f || featureOf(path) === name) continue;
      if (TEST.test(path)) f.tests.add(path);
      else if (/^src\/bootstrap\/wiring\/[^/]+\.ts$/.test(path)) {
        f.wiring.add(path);
        for (const p of imported) {
          const port = /^src\/bootstrap\/wiring\/ports\/([^/]+)\.ts$/.exec(p);
          if (port) f.ports.add(port[1]);
        }
      }
    }
  }
  return new Map([...features].sort(([a], [b]) => a.localeCompare(b)));
}

const code = (s) => "`" + s + "`";
const list = (items, fmt = code) => items.length ? items.map(fmt).join(", ") : "none";
const base = (p) => p.slice(p.lastIndexOf("/") + 1);

export function renderMap(map) {
  const lines = [
    "# Feature map",
    "",
    "Generated by `node tools/code-map.mjs --write`; `tools/test-code-map.mjs` fails when it is out of date. For each folder in `src/features/`, it lists the folder's source files, the wiring that builds and mounts it, the shared ports that wiring uses (modules in `src/bootstrap/wiring/ports/`), the action ids it defines and the tests that reach it. How the pieces fit is in [feature-ports.md](feature-ports.md).",
    "",
    "| Feature | Source files | Wiring | Shared ports | Actions | Tests |",
    "| --- | --- | --- | --- | --- | --- |"
  ];
  for (const [name, f] of map) {
    const tests = [...f.tests].sort();
    lines.push([
      "",
      code(name),
      list(f.files.sort().map(base)),
      list([...f.wiring].sort().map(base)),
      list([...f.ports].sort()),
      list([...new Set(f.actions)].sort()),
      tests.length > 6 ? `${tests.length} files` : list(tests),
      ""
    ].join(" | ").trim());
  }
  return lines.join("\n") + "\n";
}

export function duplicateTypeNames(files) {
  const seen = new Map();
  for (const { path, text } of files) {
    if (!path.startsWith("src/") || !path.endsWith(".ts") || TEST.test(path)) continue;
    for (const m of text.matchAll(/^export\s+(?:declare\s+)?(?:interface|type)\s+([A-Za-z_$][\w$]*)/gm)) {
      if (!seen.has(m[1])) seen.set(m[1], []);
      seen.get(m[1]).push(path);
    }
  }
  return [...seen].filter(([, paths]) => paths.length > 1).map(([name, paths]) => ({ name, paths }));
}

export function loadFiles(repo = REPO) {
  return listRepoFiles(repo)
    .filter((p) => SCRIPT.test(p) && (p.startsWith("src/") || p.startsWith("tests/")))
    .filter((p) => existsSync(join(repo, p)))
    .map((path) => ({ path, text: readFileSync(join(repo, path), "utf8") }));
}

export function run({ repo = REPO, write = false, print = console.log, printError = console.error } = {}) {
  const files = loadFiles(repo);
  let failed = false;
  const dupes = duplicateTypeNames(files);
  for (const d of dupes) printError(`  ${d.name}: ${d.paths.join(", ")}`);
  if (dupes.length) {
    printError("code-map: FAILED — two modules export a type with the same name; rename one, or import the one that already exists");
    failed = true;
  }
  const rendered = renderMap(buildMap(files));
  const target = join(repo, MAP_PATH);
  if (write) {
    writeFileSync(target, rendered);
    print(`code-map: wrote ${MAP_PATH}`);
  } else if (!existsSync(target) || readFileSync(target, "utf8") !== rendered) {
    printError(`code-map: FAILED — ${MAP_PATH} is out of date; run \`node tools/code-map.mjs --write\``);
    failed = true;
  }
  if (!failed) print("code-map: OK");
  return failed ? 1 : 0;
}

if (isMain(import.meta.url)) {
  process.exitCode = run({ write: process.argv[2] === "--write" });
}
